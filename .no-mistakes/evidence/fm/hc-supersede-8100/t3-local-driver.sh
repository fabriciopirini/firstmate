#!/usr/bin/env bash
set -euo pipefail
ROOT=$PWD
W=$ROOT/.test-hc/t3-local
mkdir -p "$W"
"$ROOT/bin/fm-lab-home.sh" create "$W/parent"
"$ROOT/bin/fm-lab-home.sh" create "$W/mate"
export FM_HOME="$W/parent"
unset FM_ROOT_OVERRIDE FM_STATE_OVERRIDE FM_DATA_OVERRIDE FM_CONFIG_OVERRIDE FM_PROJECTS_OVERRIDE
. "$ROOT/bin/fm-backend.sh"
fm_backend_source t3code
MATE=$W/mate
mkdir -p "$MATE/.claude" "$MATE/.codex"
cat > "$MATE/.claude/settings.local.json" <<'JSON'
{"env":{"USER_SETTING":"preserve","FM_SUPERVISOR_BACKEND":"t3code","FM_SUPERVISOR_TARGET":"mcp:synthetic-old-thread","FM_T3CODE_ENV_KEYS":"FM_SUPERVISOR_BACKEND,FM_SUPERVISOR_TARGET"},"permissions":{"deny":["Bash(rm *)"]}}
JSON
cat > "$MATE/.codex/config.toml" <<'TOML'
# Generated by Firstmate T3 Code
[shell_environment_policy]
set = { FM_SUPERVISOR_BACKEND = "t3code", FM_SUPERVISOR_TARGET = "mcp:synthetic-old-thread" }
TOML
printf 'synthetic-token-not-a-credential\n' > "$FM_HOME/config/t3code-token"
ln -s "$FM_HOME/config/t3code-token" "$MATE/config/t3code-token"
printf 'persistent backlog\n' > "$MATE/data/backlog.md"
cp "$MATE/data/backlog.md" "$W/backlog-before"
echo 'Before cleanup: synthetic owned Claude/Codex supervisor settings and token link present.'
cat "$MATE/.claude/settings.local.json" "$MATE/.codex/config.toml"
fm_backend_t3code_home_env_cleanup "$MATE"
node - "$MATE/.claude/settings.local.json" <<'JS'
const fs=require('fs'); const assert=require('assert');
const actual=JSON.parse(fs.readFileSync(process.argv[2]));
assert.deepStrictEqual(actual,{env:{USER_SETTING:'preserve'},permissions:{deny:['Bash(rm *)']}});
console.log('After cleanup:',JSON.stringify(actual));
JS
[ ! -e "$MATE/.codex/config.toml" ]
[ ! -L "$MATE/config/t3code-token" ]
[ -f "$FM_HOME/config/t3code-token" ]
cmp "$MATE/data/backlog.md" "$W/backlog-before"
echo 'Generated Codex configuration and token link removed; unrelated settings, source token, backlog preserved.'
# Probe the real T3 client against the isolated home, never the operator account.
rm "$FM_HOME/config/t3code-token"
rc=0
FM_HOME="$FM_HOME" FM_T3CODE_ORIGIN=http://127.0.0.1:1 "$ROOT/bin/fm-t3-mcp.mjs" status > "$W/status" 2>&1 || rc=$?
cat "$W/status"
echo "isolated_t3_status_exit=$rc"
[ "$rc" -ne 0 ]
